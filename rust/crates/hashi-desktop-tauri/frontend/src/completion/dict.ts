const N_ = (s: string) => s;

/** 辞書のノード。コマンド名・サブコマンド名・オプションのいずれか。 */
export interface DictNode {
  /** トークンに一致する語(`-l` のようなオプションや `/all` も含む)。 */
  word: string;
  /** 短い説明(日本語の原文)。 */
  desc: string;
  /** 続けて打てるサブコマンド。 */
  subs?: DictNode[];
  /** このノードの後に置けるオプション。 */
  opts?: DictNode[];
}

const c = (word: string, desc: string, subs?: DictNode[], opts?: DictNode[]): DictNode => ({ word, desc, subs, opts });
const o = (word: string, desc: string): DictNode => ({ word, desc });

